#include <stdint.h>
#include <stdio.h>

int main(void)
{
    // PC에서 연습하는 가상 레지스터
    volatile uint32_t ODR = 0;
    volatile uint32_t IDR = 0;
    uint32_t mask = 0;

    // 비트 번호는 오른쪽부터 0, 1, 2, 3 ... 순서
    //
    // 비트 번호:  7 6 5 4 3 2 1 0
    // 0x02:      0 0 0 0 0 0 1 0
    // 0x20:      0 0 1 0 0 0 0 0

    // ==================================================
    // 1. 특정 비트 켜기: |=
    // 다른 비트는 유지하고, 5번 비트만 1로 만든다.
    // ==================================================
    ODR = 0x02;

    ODR |= (1U << 5);

    printf("1. 5번 켜기: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0x00000022

    // 같은 코드를 다시 실행해도 계속 켜져 있다.
    ODR |= (1U << 5);

    printf("   다시 켜기: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0x00000022

    // ==================================================
    // 2. 특정 비트 끄기: &= ~
    // 다른 비트는 유지하고, 1번 비트만 0으로 만든다.
    // ==================================================
    ODR = 0x22;

    ODR &= ~(1U << 1);

    printf("2. 1번 끄기: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0x00000020

    // ==================================================
    // 3. 특정 비트 반전: ^=
    // 1이면 0으로, 0이면 1로 바꾼다.
    // ==================================================
    ODR = 0x20;

    ODR ^= (1U << 5);

    printf("3. 5번 반전: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0x00000000

    ODR ^= (1U << 5);

    printf("   다시 반전: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0x00000020 → 두 번 반전하면 원래대로

    // ==================================================
    // 4. 전체 비트 반전: ~
    // uint32_t의 32개 비트를 모두 반전한다.
    // ==================================================
    ODR = 0x00000002;

    ODR = ~ODR;

    printf("4. 전체 반전: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0xFFFFFFFD

    // ==================================================
    // 5. 여러 비트 켜기
    // |로 선택할 비트들을 합친다.
    // ==================================================
    ODR = 0x02;

    mask = (1U << 3) | (1U << 5);
    ODR |= mask;

    printf("5. 3번과 5번 켜기: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0x0000002A → 기존 1번도 유지

    // ==================================================
    // 6. 특정 비트가 1인지 확인
    // &로 골라낸 결과가 0이 아니면 ON
    // ==================================================
    IDR = 0x20;

    if ((IDR & (1U << 5)) != 0)
    {
        printf("6. 5번 비트 ON\n");
    }

    // ==================================================
    // 7. 특정 비트가 0인지 확인
    // &로 골라낸 결과가 0이면 OFF
    // ==================================================
    IDR = 0x20;

    if ((IDR & (1U << 4)) == 0)
    {
        printf("7. 4번 비트 OFF\n");
    }

    // ==================================================
    // 8. 입력 비트에 따라 출력 비트 제어
    // IDR의 6번이 1이면 ODR의 5번 켜기
    // IDR의 6번이 0이면 ODR의 5번 끄기
    // ==================================================
    IDR = 0x00;
    ODR = 0x20;

    if ((IDR & (1U << 6)) != 0)
    {
        ODR |= (1U << 5);
    }
    else
    {
        ODR &= ~(1U << 5);
    }

    printf("8. 입력에 따른 출력: 0x%08X\n", (unsigned int)ODR);
    // 결과: 0x00000000

    // ==================================================
    // 9. 선택한 비트가 모두 1인지 확인
    // 골라낸 결과가 mask 전체와 같아야 한다.
    // 다른 위치의 비트는 검사하지 않는다.
    // ==================================================
    IDR = 0x28;
    mask = (1U << 3) | (1U << 5);

    if ((IDR & mask) == mask)
    {
        printf("9. 3번과 5번 모두 ON\n");
    }

    // ==================================================
    // 10. 선택한 비트 중 하나 이상이 1인지 확인
    // 둘 다 1인 경우도 포함한다.
    // ==================================================
    IDR = 0x04;
    mask = (1U << 2) | (1U << 6);

    if ((IDR & mask) != 0)
    {
        printf("10. 2번과 6번 중 하나 이상 ON\n");
    }

    // ==================================================
    // 11. 선택한 비트가 모두 0인지 확인
    // 골라낸 결과가 0이어야 한다.
    // ==================================================
    IDR = 0x20;
    mask = (1U << 1) | (1U << 4);

    if ((IDR & mask) == 0)
    {
        printf("11. 1번과 4번 모두 OFF\n");
    }

    volatile uint32_t IDR = 0x44;
    volatile uint32_t ODR = 0x02;

    uint32_t mask = (1U << 2) | (1U << 6);

    if ((IDR & mask) == mask)
    {
        ODR |= (1U << 5);
    }
    else
    {
        ODR &= ~(1U << 5);
    }

    return 0;
}
