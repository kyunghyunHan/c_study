/*
    ============================================================
    해밀턴 순환회로 / TSP 형태의 DFS + 백트래킹
    ============================================================

    [문제]

    1번 장소가 회사이다.

    회사 1번에서 출발해서
    모든 장소를 정확히 한 번씩 방문한 후
    다시 회사 1번으로 돌아와야 한다.

    가능한 여러 방문 순서 중에서
    이동 비용의 합이 가장 작은 경로를 찾는다.


    ------------------------------------------------------------
    예제
    ------------------------------------------------------------

    5

    0  14  4  10 20
    14  0  7   8  7
    4   5  0   7 16
    11  7  9   0  2
    18  7 17   4  0


    arr[a][b]
        = a번 장소에서 b번 장소로 이동하는 비용

    예)

        arr[1][3] = 4

        1번 → 3번 이동 비용이 4라는 뜻.


    주의:
    비용은 단방향이므로

        arr[2][3]

    과

        arr[3][2]

    는 다를 수 있다.


    ------------------------------------------------------------
    DFS에서 관리해야 하는 것
    ------------------------------------------------------------

    dfs(num, cnt, cost)

    num
        현재 내가 있는 장소

    cnt
        지금까지 방문한 장소의 개수

    cost
        지금까지 사용한 총 이동 비용


    예를 들어

        1 → 3 → 2

    까지 이동했다면

        num  = 2
        cnt  = 3
        cost = arr[1][3] + arr[3][2]


    ------------------------------------------------------------
    used[i]
    ------------------------------------------------------------

    i번 장소를 이미 방문했는지를 저장한다.

        used[i] == 0
            아직 방문하지 않음

        used[i] == 1
            이미 방문함


    예를 들어

        1 → 3 → 2

    까지 방문했다면

        used[1] = 1
        used[2] = 1
        used[3] = 1
        used[4] = 0
        used[5] = 0


    ------------------------------------------------------------
    DFS 핵심 아이디어
    ------------------------------------------------------------

    현재 위치에서

        "다음에 어느 장소로 갈 것인가?"

    를 하나씩 선택한다.


    예를 들어 처음에 1번에 있다면

                        1
                 /      |      \
                2       3       4 ...

    2를 선택했다면

                        1
                        |
                        2
                      / | \
                     3  4  5

    이런 식으로 모든 방문 순서를 탐색한다.


    ------------------------------------------------------------
    백트래킹
    ------------------------------------------------------------

    다음 장소 i를 선택하면

        used[i] = 1;

    로 방문 처리한다.

    그 상태에서 DFS를 수행하고

        dfs(...);

    탐색이 끝나서 돌아오면

        used[i] = 0;

    으로 다시 원상복구한다.


    즉,

        선택
         ↓
        재귀
         ↓
        선택 취소

    구조이다.


    비숍 문제에서 했던

        drr[...] = 1;
        dfs(...);
        drr[...] = 0;

    과 완전히 같은 백트래킹 구조이다.
*/

#include <stdio.h>
#include <stdlib.h>

#define MAX (14)

/*
    장소의 개수

    문제 조건:
        1 <= n <= 13
*/
int n;

/*
    arr[a][b]

    a번 장소에서 b번 장소로 이동하는 비용

    예:

        arr[2][5] = 7

    → 2번 장소에서 5번 장소로 가는 비용이 7
*/
int arr[MAX][MAX];

/*
    지금까지 발견한 최소 비용.

    처음에는 아직 아무 경로도 찾지 못했기 때문에
    매우 큰 값으로 설정한다.

    DFS가 완성된 경로를 발견할 때마다

        현재 경로 비용 < sum

    이라면 sum을 갱신한다.
*/
int sum = 1000000000;

/*
    used[i]

    i번 장소의 방문 여부

        0 : 방문하지 않음
        1 : 방문함
*/
int used[MAX];

/*
    dfs(num, cnt, cost)

    num
        현재 위치

    cnt
        지금까지 방문한 장소의 개수

    cost
        지금까지 사용한 이동 비용


    ------------------------------------------------------------
    예:
    ------------------------------------------------------------

        1 → 3 → 2

    현재 2번에 있다면

        num = 2
        cnt = 3

        cost =
            arr[1][3]
          + arr[3][2]

    이 상태에서 아직 방문하지 않은 장소를 하나 선택해서
    다음 DFS로 이동한다.
*/
void dfs(int num, int cnt, int cost)
{
    /*
        ========================================================
        가지치기(Pruning)
        ========================================================

        현재까지 사용한 비용이 이미
        지금까지 찾은 최소 비용보다 크거나 같다면
        더 탐색할 필요가 없다.

        예:

            현재까지 비용 cost = 50

            지금까지 발견한 최소 비용 sum = 40

        여기서 앞으로 다른 장소를 방문하면
        비용은 더 증가한다.

        따라서 이 경로가 40보다 작아질 수 없다.

        즉,

            cost >= sum

        이면 이 가지(branch)는 바로 종료한다.

        이것을 "가지치기"라고 한다.
    */
    if (cost >= sum)
    {
        return;
    }

    /*
        ========================================================
        종료 조건
        ========================================================

        cnt == n

        → 모든 장소를 정확히 한 번씩 방문했다는 뜻.


        주의!

        여기서 여행이 완전히 끝난 것은 아니다.

        문제에서는 마지막으로

            현재 위치 → 회사(1번)

        로 돌아가야 한다.


        예:

            1 → 3 → 2 → 5 → 4

        여기까지 모든 장소를 방문했다면

            num = 4
            cnt = 5

        하지만 최종 경로는

            1 → 3 → 2 → 5 → 4 → 1

        이 되어야 한다.

        따라서 마지막

            arr[num][1]

        비용까지 더해야 한다.
    */
    if (cnt == n)
    {
        /*
            현재 위치에서 회사(1번)로 돌아갈 수 없다면
            완전한 순환 경로가 아니다.

            arr[num][1] == 0

            → num → 1 경로가 존재하지 않음
        */
        if (arr[num][1] == 0)
        {
            return;
        }

        /*
            지금까지의 비용
                    +
            현재 위치 → 회사 비용
        */
        int total = cost + arr[num][1];

        /*
            지금 완성한 경로가
            지금까지 발견한 최소 비용보다 작으면 갱신한다.
        */
        if (total < sum)
        {
            sum = total;
        }

        return;
    }

    /*
        ========================================================
        다음에 방문할 장소 선택
        ========================================================

        i = 다음에 방문할 장소

        1 ~ n번 장소를 전부 확인하면서

            1. 이미 방문했는가?
            2. 현재 위치에서 갈 수 있는가?

        를 확인한다.
    */
    for (int i = 1; i <= n; i++)
    {
        /*
            이미 방문했던 장소라면 다시 방문할 수 없다.

            해밀턴 순환회로에서는 각 장소를
            정확히 한 번씩 방문해야 한다.
        */
        if (used[i] == 1)
        {
            continue;
        }

        /*
            현재 위치 num에서
            i번 장소로 갈 수 없는 경우.

            arr[num][i] == 0이면 이동 불가능하다고 가정한다.
        */
        if (arr[num][i] == 0)
        {
            continue;
        }

        /*
            ====================================================
            1. 선택
            ====================================================

            다음 방문 장소로 i를 선택한다.

            따라서 i번 장소를 방문했다고 표시한다.
        */
        used[i] = 1;

        /*
            ====================================================
            2. 재귀
            ====================================================

            현재 위치:
                num → i

            방문 개수:
                cnt → cnt + 1

            이동 비용:
                cost → cost + arr[num][i]


            예를 들어

                현재 위치 num = 2
                다음 위치 i   = 4
                현재 비용      = 10
                arr[2][4]      = 8

            이라면

                dfs(4, cnt + 1, 18);

            이 된다.
        */
        dfs(
            i,
            cnt + 1,
            cost + arr[num][i]);

        /*
            ====================================================
            3. 선택 취소 (백트래킹)
            ====================================================

            i를 선택한 경우의 탐색이 모두 끝났다.

            이제 다른 경로를 탐색하기 위해
            i를 다시 "방문하지 않은 상태"로 돌려놓는다.


            예:

                        1
                       /
                      2
                     /
                    3

            1 → 2 → 3 경로를 모두 확인했다면

            used[3] = 0;

            으로 복구하고

                        1
                       /
                      2
                       \
                        4

            1 → 2 → 4

            같은 다른 선택을 탐색할 수 있다.


            이 과정이 바로 백트래킹이다.
        */
        used[i] = 0;
    }
}

int main(void)
{
    /*
        장소 개수 입력
    */
    freopen("jungol.txt", "r", stdin);
    scanf("%d", &n);

    /*
        이동 비용 입력

        arr[i][j]
            i → j 이동 비용
    */
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            scanf("%d", &arr[i][j]);
        }
    }

    /*
        출발 장소는 무조건 회사 1번이다.

        따라서 DFS를 시작하기 전에
        1번 장소는 이미 방문했다고 표시한다.

        이것을 하지 않으면 DFS 중간에

            1 → 3 → 1 → ...

        처럼 회사 1번을 다시 선택할 수 있다.
    */
    used[1] = 1;

    /*
        DFS 시작

        num  = 1
            현재 위치는 회사 1번

        cnt  = 1
            회사 1번을 이미 방문했으므로
            방문한 장소는 1개

        cost = 0
            아직 이동하지 않았으므로 비용 0
    */
    dfs(1, 1, 0);

    /*
        모든 가능한 경로를 탐색한 후
        최소 이동 비용 출력
    */
    printf("%d\n", sum);

    return 0;
}